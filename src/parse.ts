/**
 * MULTILINGUAL DOCUMENTATION THAT STAYS IN LOCKSTEP.
 *
 * Docs are Markdown, one folder per language:
 *
 *     <dir>/<locale>/_index.md                     the docs' title and own words
 *     <dir>/<locale>/<NN-section>/_section.md      a section's id and title
 *     <dir>/<locale>/<NN-section>/<NN-article>.md  an article
 *
 * Copying a folder and translating it is adding a language. Everything a
 * translator must not change (which article is which, which block is which,
 * where a generated table goes) is an id or a directive that survives
 * translation untouched. Everything else is prose.
 *
 * This module turns those files into the docs' STRUCTURE (sections, articles,
 * blocks, in order), which is the same in every language, and one BUNDLE of
 * words per language. It also reports where a translation's shape differs
 * from the original's. It has no DOM and no dependencies.
 *
 * IT IS A STRICT SUBSET OF MARKDOWN. A line it does not understand is an error
 * naming its file and line, not a paragraph that renders strangely: docs in a
 * dozen languages cannot rely on somebody noticing.
 *
 * AN ARTICLE:
 *
 *     ---
 *     id: getting-started
 *     see: [install, faq]
 *     ---
 *     # Title
 *
 *     The summary: exactly one paragraph.
 *
 *     ## A heading {#block-id}
 *
 *     A paragraph. Another paragraph after a blank line.
 *
 *     ## A table {#block-id}
 *
 *     | Column | Column |
 *     | --- | --- |
 *     | cell | cell |
 *
 *     > [!NOTE] {#block-id}
 *     > A paragraph of the note.
 *
 *     ## Generated by your app {#block-id}
 *
 *     ::pricing monthly
 *
 *     The caption: exactly one paragraph.
 *
 * Inline, a paragraph may use any inline Markdown (bold, links, code). That is
 * the renderer's business and passes through here as text.
 */

/** GitHub's alert kinds, usable as notes. */
export type NoteVariant = 'note' | 'tip' | 'important' | 'warning' | 'caution'

/** The kinds of block an article is built from. */
export type Block =
  /** A heading and one or more paragraphs. The ordinary block. */
  | { kind: 'prose'; id: string }
  /** A heading and a table whose words are all translated. */
  | { kind: 'table'; id: string }
  /** An aside the eye should stop on: `> [!NOTE] {#id}`. */
  | { kind: 'note'; id: string; variant: NoteVariant }
  /** Something your app draws (a chart, a table from data), with its caption
   *  translated: `::name arg`. */
  | { kind: 'directive'; id: string; name: string; arg?: string }

/** What a directive may be given. */
export interface DirectiveSpec {
  /**
   * The arguments it accepts. Omitted: none. A list: exactly one of these.
   * `'any'`: one argument of lower-case letters, digits, `-` and `_`.
   */
  args?: readonly string[] | 'any'
}

export interface ParseOptions {
  /** The directives articles may use, by name. None by default. */
  directives?: Readonly<Record<string, DirectiveSpec>>
}

/** A block's words, in one language. */
export interface BlockText {
  heading?: string
  body?: string[]
  columns?: string[]
  rows?: string[][]
  caption?: string
}

export interface ParsedArticle {
  id: string
  see: string[]
  title: string
  summary: string
  blocks: Block[]
  text: Record<string, BlockText>
  /** Every other frontmatter key, as written. */
  meta: Record<string, unknown>
  file: string
}

export interface ParsedSection {
  id: string
  title: string
  articles: ParsedArticle[]
  file: string
}

export interface ParsedDocs {
  locale: string
  title: string
  /** Everything in `_index.md`'s frontmatter: the docs' own words. */
  meta: Record<string, unknown>
  sections: ParsedSection[]
}

/** A mistake in a docs file, with where it is. */
export class DocsSyntaxError extends Error {
  readonly file: string
  readonly line: number
  constructor(file: string, line: number, message: string) {
    super(`${file}:${line}: ${message}`)
    this.name = 'DocsSyntaxError'
    this.file = file
    this.line = line
  }
}

// --- frontmatter -----------------------------------------------------------

/**
 * The block between the two `---` lines, and what follows it.
 *
 * The frontmatter is a small, strict YAML: maps by indentation, lists written
 * `- item` or `[a, b]`, and scalars plain or in double quotes (with JSON's
 * escapes). It is what docs need and no more.
 */
export function splitFrontmatter(
  src: string,
  file: string,
): { data: Record<string, unknown>; body: string[]; bodyLine: number } {
  const lines = src.replace(/\r\n/g, '\n').split('\n')
  if (lines[0] !== '---') throw new DocsSyntaxError(file, 1, 'a docs file begins with a `---` frontmatter block')
  const end = lines.indexOf('---', 1)
  if (end < 0) throw new DocsSyntaxError(file, 1, 'the frontmatter is never closed with `---`')
  const data = parseYaml(lines.slice(1, end), file, 2)
  return { data, body: lines.slice(end + 1), bodyLine: end + 2 }
}

function parseYaml(lines: string[], file: string, firstLine: number): Record<string, unknown> {
  let i = 0
  const indentOf = (s: string) => s.length - s.trimStart().length

  function map(indent: number): Record<string, unknown> {
    const out: Record<string, unknown> = {}
    while (i < lines.length) {
      const raw = lines[i]!
      if (raw.trim() === '' || raw.trimStart().startsWith('#')) {
        i++
        continue
      }
      const ind = indentOf(raw)
      if (ind < indent) break
      if (ind > indent) throw new DocsSyntaxError(file, firstLine + i, 'unexpected indentation')
      const m = /^([A-Za-z0-9_-]+):(.*)$/.exec(raw.trim())
      if (!m) throw new DocsSyntaxError(file, firstLine + i, `expected \`key: value\`, found \`${raw.trim()}\``)
      const key = m[1]!
      const rest = m[2]!.trim()
      i++
      if (rest !== '') {
        out[key] = scalarOrInline(rest, firstLine + i - 1)
        continue
      }
      // A nested block: a list or a map, whichever the next line starts.
      let j = i
      while (j < lines.length && lines[j]!.trim() === '') j++
      if (j >= lines.length || indentOf(lines[j]!) <= indent) {
        out[key] = ''
        continue
      }
      const childIndent = indentOf(lines[j]!)
      out[key] = lines[j]!.trimStart().startsWith('- ') ? list(childIndent) : map(childIndent)
    }
    return out
  }

  function list(indent: number): unknown[] {
    const out: unknown[] = []
    while (i < lines.length) {
      const raw = lines[i]!
      if (raw.trim() === '') {
        i++
        continue
      }
      const ind = indentOf(raw)
      if (ind < indent) break
      if (ind > indent || !raw.trimStart().startsWith('- ')) {
        throw new DocsSyntaxError(file, firstLine + i, 'a list item is written `- item`')
      }
      out.push(scalarOrInline(raw.trimStart().slice(2).trim(), firstLine + i))
      i++
    }
    return out
  }

  function scalarOrInline(text: string, line: number): unknown {
    if (text.startsWith('[')) {
      if (!text.endsWith(']')) throw new DocsSyntaxError(file, line, 'an inline list ends with `]`')
      const inner = text.slice(1, -1).trim()
      if (inner === '') return []
      return splitInline(inner, file, line).map((t) => scalar(t, line))
    }
    return scalar(text, line)
  }

  function scalar(text: string, line: number): string {
    if (text.startsWith('"')) {
      try {
        const value: unknown = JSON.parse(text)
        if (typeof value === 'string') return value
      } catch {
        // fall through to the error below
      }
      throw new DocsSyntaxError(file, line, `a quoted value is not a valid string: ${text}`)
    }
    return text
  }

  return map(0)
}

/** `a, "b, c", d` → three items, quotes respected. */
function splitInline(inner: string, file: string, line: number): string[] {
  const out: string[] = []
  let cur = ''
  let quoted = false
  for (let k = 0; k < inner.length; k++) {
    const ch = inner[k]
    if (ch === '"' && inner[k - 1] !== '\\') quoted = !quoted
    if (ch === ',' && !quoted) {
      out.push(cur.trim())
      cur = ''
      continue
    }
    cur += ch
  }
  if (quoted) throw new DocsSyntaxError(file, line, 'an unclosed quote in an inline list')
  out.push(cur.trim())
  return out
}

/** Writes a value the way the frontmatter reader reads it back. */
export function yamlScalar(value: string): string {
  const plain = /^[^\s"'[\]{}#:,&*!|>%@`-][^:#"]*$/u.test(value) && value === value.trim() && !value.includes(': ')
  return plain ? value : JSON.stringify(value)
}

// --- the body --------------------------------------------------------------

const HEADING = /^## (.+?) \{#([A-Za-z0-9_-]+)\}$/
const NOTE = /^> \[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\] \{#([A-Za-z0-9_-]+)\}$/
const DIRECTIVE = /^::([a-z][a-z0-9-]*)(?: ([a-z0-9_-]+))?$/
const ARG = /^[a-z0-9_-]+$/

/** Everything the body of an article can hold, before it is interpreted. */
type Chunk =
  | { t: 'para'; text: string; line: number }
  | { t: 'table'; rows: string[][]; line: number }
  | { t: 'directive'; name: string; arg?: string; line: number }

type Part =
  | { kind: 'head'; id: string; heading: string; chunks: Chunk[]; line: number }
  | { kind: 'note'; id: string; variant: NoteVariant; paras: string[]; line: number }

export function parseArticle(src: string, file: string, options: ParseOptions = {}): ParsedArticle {
  const { data, body, bodyLine } = splitFrontmatter(src, file)
  const id = idField(data, src, file)
  const see = listField(data, 'see', file)
  const { id: _id, see: _see, ...meta } = data

  const blocks: Block[] = []
  const text: Record<string, BlockText> = {}
  let title: string | null = null

  const parts: Part[] = []
  // What comes between the title and the first block: the summary.
  const lead: Chunk[] = []
  let current: Chunk[] = lead
  let para: string[] = []
  let paraLine = 0
  const orphans: { chunks: Chunk[]; line: number }[] = []

  const flush = () => {
    if (para.length) {
      current.push({ t: 'para', text: para.join(' '), line: paraLine })
      para = []
    }
  }

  let k = 0
  while (k < body.length) {
    const line = body[k]!
    const lineNo = bodyLine + k
    if (line.trim() === '') {
      flush()
      k++
      continue
    }
    if (line.startsWith('# ')) {
      flush()
      if (title !== null) throw new DocsSyntaxError(file, lineNo, 'an article has one `# title`')
      if (parts.length || lead.length) throw new DocsSyntaxError(file, lineNo, 'the `# title` comes first')
      title = line.slice(2).trim()
      k++
      continue
    }
    const h = HEADING.exec(line)
    if (h) {
      flush()
      const part: Extract<Part, { kind: 'head' }> = { kind: 'head', id: h[2]!, heading: h[1]!, chunks: [], line: lineNo }
      parts.push(part)
      current = part.chunks
      k++
      continue
    }
    if (line.startsWith('#')) {
      throw new DocsSyntaxError(file, lineNo, 'a block heading is written `## Heading {#block-id}`')
    }
    const n = NOTE.exec(line)
    if (n) {
      flush()
      const paras: string[] = []
      let cur: string[] = []
      k++
      while (k < body.length && body[k]!.startsWith('>')) {
        const inner = body[k]!.replace(/^> ?/, '')
        if (inner.trim() === '') {
          if (cur.length) paras.push(cur.join(' '))
          cur = []
        } else {
          cur.push(inner)
        }
        k++
      }
      if (cur.length) paras.push(cur.join(' '))
      if (!paras.length) throw new DocsSyntaxError(file, lineNo, 'a note needs at least one paragraph')
      parts.push({ kind: 'note', id: n[2]!, variant: n[1]!.toLowerCase() as NoteVariant, paras, line: lineNo })
      // What follows a note belongs to nothing until the next heading, and
      // anything written there would be lost, so it is an error below.
      current = []
      orphans.push({ chunks: current, line: lineNo })
      continue
    }
    if (line.startsWith('>')) {
      throw new DocsSyntaxError(file, lineNo, 'a quotation is a note: `> [!NOTE] {#block-id}`')
    }
    if (line.startsWith('|')) {
      flush()
      const rows: string[][] = []
      const start = lineNo
      while (k < body.length && body[k]!.startsWith('|')) {
        rows.push(cells(body[k]!, file, bodyLine + k))
        k++
      }
      if (rows.length < 2 || !rows[1]!.every((c) => /^:?-{3,}:?$/.test(c))) {
        throw new DocsSyntaxError(file, start, 'a table is a header row, a `| --- |` row, then its rows')
      }
      current.push({ t: 'table', rows: [rows[0]!, ...rows.slice(2)], line: start })
      continue
    }
    const d = DIRECTIVE.exec(line)
    if (d) {
      flush()
      current.push({ t: 'directive', name: d[1]!, arg: d[2], line: lineNo })
      k++
      continue
    }
    if (line.startsWith('::')) throw new DocsSyntaxError(file, lineNo, `\`${line}\` is not a directive: \`::name\` or \`::name argument\``)
    if (/^\s*([-*+]|\d+\.)\s/.test(line)) {
      throw new DocsSyntaxError(file, lineNo, 'lists are not part of the format; write paragraphs or a table')
    }
    if (/^(```|~~~)/.test(line.trim())) {
      throw new DocsSyntaxError(file, lineNo, 'code blocks are not part of the format; use inline `code` or a directive')
    }
    if (para.length === 0) paraLine = lineNo
    para.push(line.trim())
    k++
  }
  flush()

  if (title === null) throw new DocsSyntaxError(file, bodyLine, 'an article needs a `# title`')
  // THE SUMMARY is the one paragraph between the title and the first block.
  if (lead.length !== 1 || lead[0]!.t !== 'para') {
    throw new DocsSyntaxError(file, bodyLine, 'the title is followed by exactly one summary paragraph')
  }
  const summary = (lead[0] as Extract<Chunk, { t: 'para' }>).text
  for (const o of orphans) {
    if (o.chunks.length) {
      throw new DocsSyntaxError(file, o.chunks[0]!.line, 'text after a note needs a `## heading {#id}` of its own')
    }
  }

  const seen = new Set<string>()
  for (const part of parts) {
    if (seen.has(part.id)) throw new DocsSyntaxError(file, part.line, `the block id \`${part.id}\` is used twice`)
    seen.add(part.id)
    if (part.kind === 'note') {
      blocks.push({ kind: 'note', id: part.id, variant: part.variant })
      text[part.id] = { body: part.paras }
      continue
    }
    const { block, words } = interpret(part.id, part.heading, part.chunks, file, part.line, options)
    blocks.push(block)
    text[part.id] = words
  }

  return { id, see, title, summary, blocks, text, meta, file }
}

function interpret(
  id: string,
  heading: string,
  chunks: Chunk[],
  file: string,
  line: number,
  options: ParseOptions,
): { block: Block; words: BlockText } {
  const tables = chunks.filter((c) => c.t === 'table')
  const directives = chunks.filter((c) => c.t === 'directive')
  const paras = chunks.filter((c): c is Extract<Chunk, { t: 'para' }> => c.t === 'para')

  if (tables.length) {
    if (tables.length > 1 || directives.length || paras.length) {
      throw new DocsSyntaxError(file, line, 'a table block holds its table and nothing else')
    }
    const [header, ...rows] = (tables[0] as Extract<Chunk, { t: 'table' }>).rows
    return { block: { kind: 'table', id }, words: { heading, columns: header, rows } }
  }
  if (directives.length) {
    const d = directives[0] as Extract<Chunk, { t: 'directive' }>
    if (directives.length > 1) throw new DocsSyntaxError(file, d.line, 'one directive per block')
    if (chunks[0] !== d) throw new DocsSyntaxError(file, d.line, 'the directive comes first in its block')
    if (paras.length !== 1) throw new DocsSyntaxError(file, d.line, 'a directive is followed by exactly one caption paragraph')
    return { block: directiveBlock(id, d, file, options), words: { heading, caption: paras[0]!.text } }
  }
  if (!paras.length) throw new DocsSyntaxError(file, line, 'a block with a heading needs at least one paragraph')
  return { block: { kind: 'prose', id }, words: { heading, body: paras.map((p) => p.text) } }
}

function directiveBlock(id: string, d: Extract<Chunk, { t: 'directive' }>, file: string, options: ParseOptions): Block {
  const known = options.directives ?? {}
  const spec = Object.hasOwn(known, d.name) ? known[d.name] : undefined
  if (!spec) {
    const names = Object.keys(known)
    const hint = names.length ? `; known: ${names.map((x) => `\`::${x}\``).join(', ')}` : '; this project declares none'
    throw new DocsSyntaxError(file, d.line, `unknown directive \`::${d.name}\`${hint}`)
  }
  const args = spec.args
  if (args === undefined) {
    if (d.arg !== undefined) throw new DocsSyntaxError(file, d.line, `\`::${d.name}\` takes no argument`)
    return { kind: 'directive', id, name: d.name }
  }
  if (d.arg === undefined || (args !== 'any' && !args.includes(d.arg)) || !ARG.test(d.arg)) {
    const what = args === 'any' ? 'one argument' : args.join(', ')
    throw new DocsSyntaxError(file, d.line, `\`::${d.name}\` takes ${what}`)
  }
  return { kind: 'directive', id, name: d.name, arg: d.arg }
}

/** `| a | b \| c |` → ["a", "b | c"]. */
function cells(line: string, file: string, lineNo: number): string[] {
  const trimmed = line.trim()
  if (!trimmed.endsWith('|')) throw new DocsSyntaxError(file, lineNo, 'a table row ends with `|`')
  const inner = trimmed.slice(1, -1)
  const out: string[] = []
  let cur = ''
  for (let k = 0; k < inner.length; k++) {
    if (inner[k] === '\\' && inner[k + 1] === '|') {
      cur += '|'
      k++
      continue
    }
    if (inner[k] === '|') {
      out.push(cur.trim())
      cur = ''
      continue
    }
    cur += inner[k]
  }
  out.push(cur.trim())
  return out
}

function stringField(data: Record<string, unknown>, key: string, file: string): string {
  const v = data[key]
  if (typeof v !== 'string' || v === '') throw new DocsSyntaxError(file, 1, `the frontmatter needs \`${key}\``)
  return v
}

/**
 * AN ID IS PART OF AN ADDRESS: a page, a sitemap entry, a link. It is
 * lower-case letters, digits, `-` and `_`, and nothing else reaches a path.
 */
const ID = /^[a-z0-9_-]+$/

function idField(data: Record<string, unknown>, src: string, file: string): string {
  const id = stringField(data, 'id', file)
  if (!ID.test(id)) {
    const at = src
      .replace(/\r\n/g, '\n')
      .split('\n')
      .findIndex((l) => /^id:/.test(l))
    throw new DocsSyntaxError(file, at >= 0 ? at + 1 : 1, `an id is lower-case letters, digits, \`-\` and \`_\`, not \`${id}\``)
  }
  return id
}

function listField(data: Record<string, unknown>, key: string, file: string): string[] {
  const v = data[key]
  if (v === undefined || v === '') return []
  if (!Array.isArray(v) || !v.every((x) => typeof x === 'string')) {
    throw new DocsSyntaxError(file, 1, `\`${key}\` is a list of article ids`)
  }
  return v as string[]
}

// --- sections and the whole ------------------------------------------------

/** A section folder's `_section.md`: its id, and its title as the `# heading`. */
export function parseSection(src: string, file: string): { id: string; title: string; meta: Record<string, unknown> } {
  const { data, body, bodyLine } = splitFrontmatter(src, file)
  const id = idField(data, src, file)
  const { id: _id, ...meta } = data
  return { id, title: onlyTitle(body, bodyLine, file), meta }
}

/** `_index.md`: the docs' own words in the frontmatter, the title below. */
export function parseIndex(src: string, file: string): { title: string; meta: Record<string, unknown> } {
  const { data, body, bodyLine } = splitFrontmatter(src, file)
  return { title: onlyTitle(body, bodyLine, file), meta: data }
}

function onlyTitle(body: string[], bodyLine: number, file: string): string {
  const lines = body.filter((l) => l.trim() !== '')
  if (lines.length !== 1 || !lines[0]!.startsWith('# ')) {
    throw new DocsSyntaxError(file, bodyLine, 'this file holds its frontmatter and one `# title` line')
  }
  return lines[0]!.slice(2).trim()
}

/** One file of a language folder: its path inside the folder, and its text. */
export interface DocsFile {
  path: string
  content: string
}

/** The name of the file at the top of every language folder. */
export const INDEX_FILE = '_index.md'
/** The name of the file at the top of every section folder. */
export const SECTION_FILE = '_section.md'

/**
 * A language folder, read whole.
 *
 * ORDER IS THE FILE NAMES'. `01-start/` comes before `02-guides/`, and
 * `00-intro.md` before `01-install.md`: reordering is renaming a file, and a
 * translator who copies the folder copies the order with it.
 */
export function parseDocs(locale: string, files: DocsFile[], options: ParseOptions = {}): ParsedDocs {
  const at = (p: string) => `${locale}/${p}`
  const indexFile = files.find((f) => f.path === INDEX_FILE)
  if (!indexFile) throw new DocsSyntaxError(at(INDEX_FILE), 1, `every language folder has an \`${INDEX_FILE}\``)
  const { title, meta } = parseIndex(indexFile.content, at(INDEX_FILE))

  const bySection = new Map<string, DocsFile[]>()
  for (const f of files) {
    if (f.path === INDEX_FILE) continue
    const parts = f.path.split('/')
    if (parts.length !== 2 || !parts[1]!.endsWith('.md')) {
      throw new DocsSyntaxError(at(f.path), 1, 'a docs file lives at `<section>/<article>.md`')
    }
    const list = bySection.get(parts[0]!) ?? []
    list.push(f)
    bySection.set(parts[0]!, list)
  }

  const sections: ParsedSection[] = []
  const ids = new Set<string>()
  const sectionIds = new Set<string>()
  for (const folder of [...bySection.keys()].sort()) {
    const inFolder = bySection.get(folder)!
    const sectionFile = inFolder.find((f) => f.path.endsWith(`/${SECTION_FILE}`))
    if (!sectionFile) throw new DocsSyntaxError(at(`${folder}/${SECTION_FILE}`), 1, `every section folder has a \`${SECTION_FILE}\``)
    const head = parseSection(sectionFile.content, at(sectionFile.path))
    if (sectionIds.has(head.id)) throw new DocsSyntaxError(at(sectionFile.path), 1, `the section id \`${head.id}\` is used twice`)
    sectionIds.add(head.id)
    const articles = inFolder
      .filter((f) => f !== sectionFile)
      .sort((a, b) => a.path.localeCompare(b.path))
      .map((f) => parseArticle(f.content, at(f.path), options))
    for (const a of articles) {
      if (ids.has(a.id)) throw new DocsSyntaxError(a.file, 1, `the article id \`${a.id}\` is used twice`)
      ids.add(a.id)
    }
    sections.push({ id: head.id, title: head.title, articles, file: at(sectionFile.path) })
  }
  for (const s of sections) {
    for (const a of s.articles) {
      for (const id of a.see) {
        if (!ids.has(id)) throw new DocsSyntaxError(a.file, 1, `\`see\` names \`${id}\`, which is no article`)
      }
    }
  }
  return { locale, title, meta, sections }
}

/** A section of the docs' structure: the same in every language. */
export interface StructureSection {
  id: string
  articles: { id: string; blocks: Block[]; see?: string[] }[]
}

/** The shape every language shares, taken from one of them. */
export function toStructure(docs: ParsedDocs): StructureSection[] {
  return docs.sections.map((s) => ({
    id: s.id,
    articles: s.articles.map((a) => ({
      id: a.id,
      blocks: a.blocks,
      ...(a.see.length ? { see: a.see } : {}),
    })),
  }))
}

/**
 * One language's words as one nested object, ready to load as a translation
 * namespace (i18next, for one):
 *
 *     { title, ...indexFrontmatter,
 *       sections: { <section>: title },
 *       articles: { <article>: { title, summary, sections: { <block>: BlockText } } } }
 */
export function toBundle(docs: ParsedDocs): Record<string, unknown> {
  const articles: Record<string, unknown> = {}
  const sections: Record<string, string> = {}
  for (const s of docs.sections) {
    sections[s.id] = s.title
    for (const a of s.articles) {
      articles[a.id] = { title: a.title, summary: a.summary, sections: a.text }
    }
  }
  return { title: docs.title, ...docs.meta, articles, sections }
}

/** One way a translation's shape differs from the original's. */
export interface Difference {
  /**
   * - `missing`: the translation has no such article (a reader can fall back
   *   to the original);
   * - `extra`: the translation has an article the original does not;
   * - `moved`: the article is in another section;
   * - `blocks`: its blocks differ in id, kind, order or directive;
   * - `see`: its `see` list differs;
   * - `counts`: a block has a different number of paragraphs, rows, columns
   *   or cells.
   */
  kind: 'missing' | 'extra' | 'moved' | 'blocks' | 'see' | 'counts'
  /** The translation's file, or its locale for a missing article. */
  file: string
  message: string
}

/**
 * Where a translation's shape differs from the original's.
 *
 * THE SAME DOCS IN EVERY LANGUAGE: the same sections and articles in the same
 * order, the same blocks of the same kinds, the same number of paragraphs and
 * of table rows and columns. A translation may say anything; it may not
 * quietly drop a paragraph or a row.
 */
export function shapeDifferences(original: ParsedDocs, translation: ParsedDocs): Difference[] {
  const out: Difference[] = []
  const add = (kind: Difference['kind'], file: string, message: string) => out.push({ kind, file, message: `${file}: ${message}` })
  const shape = (g: ParsedDocs) => new Map(g.sections.flatMap((s) => s.articles.map((a) => [a.id, { section: s.id, a }] as const)))
  const theirs = shape(translation)
  for (const s of original.sections) {
    for (const a of s.articles) {
      const t = theirs.get(a.id)
      if (!t) {
        add('missing', translation.locale, `no article \`${a.id}\` (${a.file})`)
        continue
      }
      if (t.section !== s.id) add('moved', t.a.file, `in section \`${t.section}\`, the original has it in \`${s.id}\``)
      if (JSON.stringify(t.a.blocks) !== JSON.stringify(a.blocks)) {
        add('blocks', t.a.file, `its blocks differ from ${a.file}`)
        continue
      }
      if (JSON.stringify(t.a.see) !== JSON.stringify(a.see)) add('see', t.a.file, `\`see\` differs from ${a.file}`)
      for (const b of a.blocks) {
        const mine = a.text[b.id]!
        const other = t.a.text[b.id]!
        const count = (x: BlockText) =>
          [x.body?.length ?? 0, x.rows?.length ?? 0, x.columns?.length ?? 0, (x.rows ?? []).map((r) => r.length).join(',')].join('/')
        if (count(mine) !== count(other)) {
          add('counts', t.a.file, `block \`${b.id}\` has ${count(other)} (paragraphs/rows/columns/cells), the original ${count(mine)}`)
        }
      }
    }
  }
  const known = new Set(original.sections.flatMap((s) => s.articles.map((a) => a.id)))
  for (const [id, t] of theirs) {
    if (!known.has(id)) add('extra', t.a.file, `the original has no article \`${id}\``)
  }
  return out
}
